ALL_ENDPOINTS = endpoints()
WEB_ENDPOINTS = [e for e in ALL_ENDPOINTS if not e.is_api_operation]
OPERATIONS = api_operations()
NON_PUBLIC = [e for e in WEB_ENDPOINTS if e.key not in PUBLIC]
STAFF_ONLY = [e for e in WEB_ENDPOINTS if isinstance(classify(e), StaffOnly)]
VENDOR_SCOPED_WEB = [
    e for e in WEB_ENDPOINTS if isinstance(classify(e), VendorScoped | VendorScopedList)
]
KEYED_OPERATIONS = [op for op in OPERATIONS if op.scopes]

REFUSED = frozenset({401, 403, 404, 405})
WRITE = re.compile(r'^\s*(?:INSERT\s+INTO|UPDATE|DELETE\s+FROM)\s+"?(\w+)"?', re.IGNORECASE)


def sample_path(endpoint: Endpoint) -> str:
    """A path that routes to `endpoint`, with the sample parameters of its tenancy declaration."""
    access = classify(endpoint)
    if isinstance(access, NoVendorData) and access.path:
        return access.path
    kwargs = access.kwargs if isinstance(access, NoVendorData | StaffOnly) else {}
    return endpoint.path(**{name: kwargs.get(name, "0") for name in endpoint.params})


def routes_to(endpoint: Endpoint, path: str) -> bool:
    match = resolve(path)
    found = match.view_name if match.url_name else match.route
    return found == endpoint.key


def sign_in_paths() -> frozenset[str]:
    return frozenset({reverse("admin:login"), reverse("wagtailadmin_login")})


def is_refusal(response: HttpResponseBase) -> bool:
    """401/403/404/405, or a redirect to a sign-in page."""
    if response.status_code in REFUSED:
        return True
    if 300 <= response.status_code < 400:
        return urlsplit(response.headers.get("Location", "")).path in sign_in_paths()
    return False


def describe(response: HttpResponseBase) -> str:
    location = response.headers.get("Location")
    return f"{response.status_code}" + (f" → {location}" if location else "")


@contextmanager
def written_tables() -> Iterator[set[str]]:
    """The tables written by the statements run inside the block."""
    tables: set[str] = set()
    with CaptureQueriesContext(connection) as queries:
        yield tables
    for query in queries.captured_queries:
        match = WRITE.match(query["sql"])
        if match:
            tables.add(match.group(1))


def is_editors_admin(endpoint: Endpoint) -> bool:
    """Served under the Wagtail admin (`/admin/`), whose API views are CSRF-exempt."""
    return endpoint.route.startswith(CMS_ADMIN_ROUTE)


def staff_client(*, raise_request_exception: bool = True) -> Client:
    client = Client(enforce_csrf_checks=True, raise_request_exception=raise_request_exception)
    verified_login(client, UserFactory.create(superuser=True))
    return client


# --- Guards: the allow-lists name real endpoints


def test_public_allow_list_has_no_stale_entries() -> None:
    keys = {e.key for e in WEB_ENDPOINTS}
    stale = sorted(set(PUBLIC) - keys)
    assert not stale, "No such endpoint any more, remove from PUBLIC: " + ", ".join(stale)


def test_csrf_exempt_views_are_declared() -> None:
    exempt = {e.key for e in WEB_ENDPOINTS if getattr(e.callback, "csrf_exempt", False)}
    # Wagtail's admin API (django-ninja) and wagtail-localize's (DRF) views are marked exempt but
    # either check the token themselves (DRF SessionAuthentication) or take no POST at all:
    # `test_post_without_csrf_token_is_refused` proves it for each of them.
    editors_admin = {e.key for e in WEB_ENDPOINTS if is_editors_admin(e)}
    undeclared = sorted(exempt - set(CSRF_EXEMPT) - editors_admin)
    stale = sorted(set(CSRF_EXEMPT) - exempt)
    assert not undeclared, "Declare in tests.security_registry.CSRF_EXEMPT: " + ", ".join(
        undeclared
    )
    assert not stale, "No longer CSRF-exempt, remove from CSRF_EXEMPT: " + ", ".join(stale)


def test_every_non_public_sample_path_reaches_its_endpoint() -> None:
    """The anonymous checks below prove nothing if the sample path routes somewhere else."""
    wrong = sorted(e.key for e in NON_PUBLIC if not routes_to(e, sample_path(e)))
    assert not wrong, "Sample paths route elsewhere: " + ", ".join(wrong)


def test_sign_in_pages_are_public() -> None:
    client = Client()
    for path in sign_in_paths():
        assert client.get(path).status_code == 200, path


# --- Anonymous visitors


@pytest.mark.parametrize("method", ["GET", "POST"])
@pytest.mark.parametrize("endpoint", NON_PUBLIC, ids=lambda e: e.key)
def test_anonymous_visitor_is_refused(endpoint: Endpoint, method: str, client: Client) -> None:
    path = sample_path(endpoint)
    with written_tables() as tables:
        response = client.generic(method, path)
    assert is_refusal(response), (
        f"{endpoint.key}: an anonymous {method} {path} got {describe(response)}. If the page is "
        "meant to be public, list it in tests.security_registry.PUBLIC with the reason."
    )
    assert tables <= GET_WRITES_ALLOWED, f"{endpoint.key}: anonymous {method} wrote {tables}"


@pytest.mark.parametrize("operation", OPERATIONS, ids=lambda op: op.key)
def test_api_operation_without_key_is_refused(operation: ApiOperation, client: Client) -> None:
    response = client.generic(operation.method, sample_path(operation.endpoint))
    assert response.status_code == 401, f"{operation.key}: no key got {describe(response)}"


@pytest.mark.parametrize("operation", OPERATIONS, ids=lambda op: op.key)
def test_api_operation_with_unknown_key_is_refused(operation: ApiOperation, client: Client) -> None:
    headers = {"Authorization": f"Bearer {secrets.token_urlsafe(32)}"}
    response = client.generic(operation.method, sample_path(operation.endpoint), headers=headers)
    assert response.status_code == 401, f"{operation.key}: unknown key got {describe(response)}"


@pytest.mark.parametrize("operation", KEYED_OPERATIONS, ids=lambda op: op.key)
def test_api_key_without_the_operation_scope_is_refused(
    operation: ApiOperation, client: Client
) -> None:
    other = "catalog:write" if ANY_KEY_SCOPE in operation.scopes else ANY_KEY_SCOPE
    assert other not in operation.scopes
    _, key = ApiClientFactory.create_with_key(scopes=[other])
    response = client.generic(
        operation.method,
        sample_path(operation.endpoint),
        headers={"Authorization": f"Bearer {key}"},
    )
    assert response.status_code == 403, (
        f"{operation.key}: a key without {', '.join(operation.scopes)} got {describe(response)}"
    )


# --- CSRF and GET side effects, as a signed-in superuser


@pytest.mark.parametrize("endpoint", WEB_ENDPOINTS, ids=lambda e: e.key)
def test_post_without_csrf_token_is_refused(endpoint: Endpoint) -> None:
    client = staff_client()
    path = sample_path(endpoint)
    with written_tables() as tables:
        response = client.post(path)
    if endpoint.key in CSRF_EXEMPT:
        assert response.status_code >= 400, (
            f"{endpoint.key} is CSRF-exempt ({CSRF_EXEMPT[endpoint.key]}), but an unsigned POST "
            f"got {describe(response)}"
        )
    elif is_editors_admin(endpoint) and getattr(endpoint.callback, "csrf_exempt", False):
        # Wagtail's admin API and wagtail-localize: DRF checks the token itself (403); a view
        # without a POST handler answers 405 and changes nothing.
        assert response.status_code in {403, 405}, (
            f"{endpoint.key}: a POST without the CSRF token got {describe(response)}"
        )
    else:
        assert response.status_code == 403, (
            f"{endpoint.key}: a POST without the CSRF token got {describe(response)}"
        )
    assert tables <= GET_WRITES_ALLOWED, f"{endpoint.key}: the refused POST wrote {tables}"


@pytest.mark.parametrize("operation", OPERATIONS, ids=lambda op: op.key)
def test_api_operation_ignores_the_session_cookie(operation: ApiOperation) -> None:
    """API v1 is CSRF-exempt, which is safe only because a session never authenticates it."""
    response = staff_client().generic(operation.method, sample_path(operation.endpoint))
    assert response.status_code == 401, (
        f"{operation.key}: a signed-in superuser without an API key got {describe(response)} "
        f"({API_CSRF_REASON})"
    )


@pytest.mark.parametrize("endpoint", WEB_ENDPOINTS, ids=lambda e: e.key)
def test_get_has_no_side_effects(endpoint: Endpoint) -> None:
    # Wagtail's error test page (`/admin/failwhale/`) raises on purpose: only the writes count.
    client = staff_client(raise_request_exception=False)
    path = sample_path(endpoint)
    allowed = GET_WRITES_ALLOWED | set(GET_WRITES_BY_ENDPOINT.get(endpoint.key, {}))
    with written_tables() as tables:
        client.get(path)
    assert tables <= allowed, (
        f"{endpoint.key}: GET {path} wrote {sorted(tables - allowed)}; a GET must not change "
        "data (use POST behind the CSRF token)"
    )


def test_get_write_exceptions_have_no_stale_entries() -> None:
    keys = {e.key for e in WEB_ENDPOINTS}
    stale = sorted(set(GET_WRITES_BY_ENDPOINT) - keys)
    assert not stale, "No such endpoint, remove from GET_WRITES_BY_ENDPOINT: " + ", ".join(stale)


