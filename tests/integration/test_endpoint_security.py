@pytest.mark.parametrize(
    "endpoint", [e for e in WEB_ENDPOINTS if e not in STAFF_ONLY], ids=lambda e: e.key
)
def test_a_customer_sees_no_vendor_data(
    endpoint: Endpoint, client: Client, customer: User, cross_tenant: CrossTenant
) -> None:
    """Every page a customer may open, with one object of every vendor-owned model at Vendor B."""
    seeded = cross_tenant.seed_b()
    access = classify(endpoint)
    as_customer = replace(cross_tenant, a=replace(cross_tenant.a, owner=customer))
    if isinstance(access, NoVendorData) and access.login is not None:
        access.login(client, as_customer)
    else:
        client.force_login(customer)
    response = client.get(sample_path(endpoint))
    body = "" if response.streaming else response.content.decode(errors="replace")
    body += response.headers.get("Location", "")
    leaked = [marker for marker in cross_tenant.markers(*seeded) if marker and marker in body]
    assert not leaked, f"{endpoint.key}: a customer sees Vendor B's data: {leaked}"


# --- IDOR: every route that carries an identifier is covered by a cross-tenant test or reviewed

TENANT_TESTED = (VendorScoped, VendorScopedList, StaffOnly)


def test_every_web_route_with_an_identifier_is_tenant_tested_or_reviewed() -> None:
    unchecked = sorted(
        e.key
        for e in WEB_ENDPOINTS
        if e.params and not isinstance(classify(e), TENANT_TESTED) and e.key not in IDOR_REVIEWED
    )
    assert not unchecked, (
        "These routes take an identifier but no cross-tenant test reaches them: declare them "
        "VendorScoped in tests.tenancy_registry, or list them in "
        "tests.security_registry.IDOR_REVIEWED with what protects them: " + ", ".join(unchecked)
    )


def test_every_api_operation_with_an_identifier_is_vendor_scoped_or_reviewed() -> None:
    unchecked = sorted(
        op.key
        for op in OPERATIONS
        if op.endpoint.params
        and not isinstance(API_OPERATIONS.get(op.key), VendorScoped | VendorScopedList)
        and op.key not in IDOR_REVIEWED
    )
    assert not unchecked, (
        "Declare these API operations VendorScoped in tests.tenancy_registry.API_OPERATIONS or "
        "review them in tests.security_registry.IDOR_REVIEWED: " + ", ".join(unchecked)
    )


def test_idor_review_has_no_stale_entries() -> None:
    keys = {e.key for e in WEB_ENDPOINTS} | {op.key for op in OPERATIONS}
    stale = sorted(set(IDOR_REVIEWED) - keys)
    assert not stale, "No such endpoint, remove from IDOR_REVIEWED: " + ", ".join(stale)


def test_a_user_cannot_remove_another_users_second_factor(client: Client) -> None:
    owner, intruder = UserFactory.create(), UserFactory.create()
    theirs = TOTPDeviceFactory.create(user=owner)
    TOTPDeviceFactory.create(user=intruder)  # a factor of their own, so a removal is allowed
    verified_login(client, intruder)
    path = reverse("mfa:remove_device", kwargs={"kind": "totp", "public_id": str(theirs.pk)})

    response = client.post(path)

    assert response.status_code == 404
    assert type(theirs).objects.filter(pk=theirs.pk).exists()


def test_a_claim_link_opens_only_its_own_vendor(client: Client) -> None:
    """A claimant of Vendor A who swaps Vendor B's public id into the claim URL is refused."""
    vendor_a = imported_vendor()
    vendor_b = VendorFactory.create(italian_company=True, contact_email="legal@vendor-b.example")
    send_link(vendor_b)
    open_link(client, send_link(vendor_a))

    page = client.get(claim_url(vendor_b))
    answer = confirm_identity(client, vendor_b, vendor_b.vat_number)

    assert page.status_code == 403
    assert vendor_b.legal_name not in page.content.decode()
    assert answer.status_code == 403
    claim_b = VendorClaim.objects.get(vendor=vendor_b)
    assert claim_b.status == VendorClaim.Status.OPEN
    assert claim_b.confirmed_link == ""


